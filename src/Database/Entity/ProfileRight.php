#[SchemaIndex('IDX_6E4E481771A4E89E', ['`profiles_id`'])]
#[SchemaIndex('unicity', ['profiles_id', 'name'], unique: true, postgresqlName: 'glpi_profilerights_unicity')]
class ProfileRight
{
    #[ORM\ManyToOne(targetEntity: Profile::class)]
    #[ORM\JoinColumn(name: 'profiles_id', referencedColumnName: 'id', nullable: false, onDelete: 'RESTRICT', foreignKeyName: 'fk_profilerights_profiles_id', options: ['default' => 0])]
    #[ApplicationManaged]
    public ?Profile $profiles = null;

    #[ORM\Id]
    #[ORM\GeneratedValue(strategy: 'IDENTITY')]
    #[ORM\Column(name: '`id`', type: 'bigint', nullable: false)]
    public ?int $id = null;

    #[ORM\Column(name: '`name`', type: 'string', length: 255, nullable: true)]
    public ?string $name = null;

    #[ORM\Column(name: '`rights`', type: 'integer', nullable: false, options: ['default' => '0'])]
    public int $rights = 0;
}
